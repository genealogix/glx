func TestMigrateStripStaleEventTitles_StripsAutoGeneratedShapes(t *testing.T) {
	archive := &glxlib.GLXFile{
		Persons: map[string]*glxlib.Person{
			"person-john": {Properties: map[string]any{"name": "John Smith"}},
			"person-robert": {Properties: map[string]any{
				"name": map[string]any{"value": "Robert Webb"},
			}},
			"person-jane": {Properties: map[string]any{"name": "Jane Miller"}},
		},
		Events: map[string]*glxlib.Event{
			"event-birth": {
				Title: "Birth of John Smith (1850)",
				Type:  glxlib.EventTypeBirth,
				Date:  "1850-03-15",
				Participants: []glxlib.Participant{
					{Person: "person-john", Role: glxlib.ParticipantRolePrincipal},
				},
			},
			// The buggy day-as-year suffix from #1025.
			"event-burial": {
				Title: "Burial of John Smith (15)",
				Type:  glxlib.EventTypeBurial,
				Participants: []glxlib.Participant{
					{Person: "person-john", Role: glxlib.ParticipantRolePrincipal},
				},
			},
			"event-marriage": {
				Title: "Marriage of Robert Webb and Jane Miller (1850)",
				Type:  glxlib.EventTypeMarriage,
				Participants: []glxlib.Participant{
					{Person: "person-robert", Role: glxlib.ParticipantRoleSpouse},
					{Person: "person-jane", Role: glxlib.ParticipantRoleSpouse},
				},
			},
			"event-bare": {
				Title: "Census (1863)",
				Type:  glxlib.EventTypeCensus,
			},
		},
	}

	report := migrateStripStaleEventTitles(archive)

	assert.Equal(t, 4, report.EventTitleYearsStripped)
	assert.Equal(t, "Birth of John Smith", archive.Events["event-birth"].Title)
	assert.Equal(t, "Burial of John Smith", archive.Events["event-burial"].Title)
	assert.Equal(t, "Marriage of Robert Webb and Jane Miller", archive.Events["event-marriage"].Title)
	assert.Equal(t, "Census", archive.Events["event-bare"].Title)
	// The year stays where it belongs — the event's date field.
	assert.Equal(t, glxlib.DateString("1850-03-15"), archive.Events["event-birth"].Date)
}

func TestMigrateStripStaleEventTitles_PreservesHandAuthoredTitles(t *testing.T) {
	archive := &glxlib.GLXFile{
		Persons: map[string]*glxlib.Person{
			"person-john": {Properties: map[string]any{"name": "John Smith"}},
		},
		Events: map[string]*glxlib.Event{
			// The literal example from the Event.Title doc comment.
			"event-census": {
				Title: "1860 Census — Webb Household",
				Type:  glxlib.EventTypeCensus,
				Participants: []glxlib.Participant{
					{Person: "person-john", Role: glxlib.ParticipantRolePrincipal},
				},
			},
			// Trailing year, but the prefix is not a derivable auto-title.
			"event-reunion": {
				Title: "Family reunion (1955)",
				Type:  glxlib.EventTypeGeneric,
				Participants: []glxlib.Participant{
					{Person: "person-john", Role: glxlib.ParticipantRolePrincipal},
				},
			},
			// Non-digit parenthetical.
			"event-household": {
				Title: "Census (Webb Household)",
				Type:  glxlib.EventTypeCensus,
			},
			// Auto shape but the participant's name doesn't match.
			"event-renamed": {
				Title: "Birth of Johann Schmidt (1850)",
				Type:  glxlib.EventTypeBirth,
				Participants: []glxlib.Participant{
					{Person: "person-john", Role: glxlib.ParticipantRolePrincipal},
				},
			},
			"event-untitled": {
				Type: glxlib.EventTypeBirth,
			},
		},
	}

	report := migrateStripStaleEventTitles(archive)

	assert.Equal(t, 0, report.EventTitleYearsStripped)
	assert.Equal(t, "1860 Census — Webb Household", archive.Events["event-census"].Title)
	assert.Equal(t, "Family reunion (1955)", archive.Events["event-reunion"].Title)
	assert.Equal(t, "Census (Webb Household)", archive.Events["event-household"].Title)
	assert.Equal(t, "Birth of Johann Schmidt (1850)", archive.Events["event-renamed"].Title)
}

// TestMigrateStripStaleEventTitles_IgnoresASSOParticipants confirms the gate
// is derived only from principal/spouse names — witness and officiant
// participants (appended by ASSO import after the title was generated) must
// neither block a legitimate strip nor enable one under the wrong name.
func TestMigrateStripStaleEventTitles_IgnoresASSOParticipants(t *testing.T) {
	archive := &glxlib.GLXFile{
		Persons: map[string]*glxlib.Person{
			"person-john":    {Properties: map[string]any{"name": "John Smith"}},
			"person-witness": {Properties: map[string]any{"name": "Willa Witness"}},
		},
		Events: map[string]*glxlib.Event{
			// Witness present: the principal-derived title still strips.
			"event-with-witness": {
				Title: "Baptism of John Smith (1850)",
				Type:  glxlib.EventTypeBaptism,
				Participants: []glxlib.Participant{
					{Person: "person-john", Role: glxlib.ParticipantRolePrincipal},
					{Person: "person-witness", Role: glxlib.ParticipantRoleWitness},
				},
			},
			// A title matching only the witness's name is not an auto shape.
			"event-witness-titled": {
				Title: "Baptism of Willa Witness (1850)",
				Type:  glxlib.EventTypeBaptism,
				Participants: []glxlib.Participant{
					{Person: "person-john", Role: glxlib.ParticipantRolePrincipal},
					{Person: "person-witness", Role: glxlib.ParticipantRoleWitness},
				},
			},
		},
	}

	report := migrateStripStaleEventTitles(archive)

	assert.Equal(t, 1, report.EventTitleYearsStripped)
	assert.Equal(t, "Baptism of John Smith", archive.Events["event-with-witness"].Title)
	assert.Equal(t, "Baptism of Willa Witness (1850)", archive.Events["event-witness-titled"].Title)
}

