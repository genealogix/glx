// TestMigrateStripStaleEventTitles_IsIdempotent runs the migration twice and
// confirms the second run is a no-op: a cleaned title no longer carries a
// suffix to match.
func TestMigrateStripStaleEventTitles_IsIdempotent(t *testing.T) {
	archive := &glxlib.GLXFile{
		Persons: map[string]*glxlib.Person{
			"person-john": {Properties: map[string]any{"name": "John Smith"}},
		},
		Events: map[string]*glxlib.Event{
			"event-birth": {
				Title: "Birth of John Smith (1850)",
				Type:  glxlib.EventTypeBirth,
				Participants: []glxlib.Participant{
					{Person: "person-john", Role: glxlib.ParticipantRolePrincipal},
				},
			},
		},
	}

	first := migrateStripStaleEventTitles(archive)
	require.Equal(t, 1, first.EventTitleYearsStripped)

	second := migrateStripStaleEventTitles(archive)
	assert.Equal(t, 0, second.EventTitleYearsStripped)
	assert.Equal(t, "Birth of John Smith", archive.Events["event-birth"].Title)
}

// TestMigrateArchive_StripEventTitleYearSingleFileRoundTrip exercises the full
// archive load → migrate → write → reload pipeline on a single-file archive.
func TestMigrateArchive_StripEventTitleYearSingleFileRoundTrip(t *testing.T) {
	dir := t.TempDir()
	archivePath := filepath.Join(dir, "archive.glx")

	preMigration := `metadata:
  glx_version: "1.0"
persons:
  person-john:
    properties:
      name:
        value: "John Smith"
events:
  event-birth:
    title: "Birth of John Smith (1850)"
    type: birth
    date: "1850"
    participants:
      - person: person-john
        role: principal
  event-custom:
    title: "Family reunion (1955)"
    type: event
    participants:
      - person: person-john
        role: principal
`
	require.NoError(t, os.WriteFile(archivePath, []byte(preMigration), 0o600))

	t.Cleanup(func() { migrateStripEventTitleYear = false })
	migrateStripEventTitleYear = true
	require.NoError(t, migrateArchive(archivePath))

	written, err := os.ReadFile(archivePath)
	require.NoError(t, err)
	assert.NotContains(t, string(written), "Birth of John Smith (1850)")
	assert.Contains(t, string(written), "Birth of John Smith")
	assert.Contains(t, string(written), "Family reunion (1955)")

	reloaded, err := readSingleFileArchive(archivePath, false)
	require.NoError(t, err)
	require.Len(t, reloaded.Events, 2)
	assert.Equal(t, "Birth of John Smith", reloaded.Events["event-birth"].Title)
	assert.Equal(t, glxlib.DateString("1850"), reloaded.Events["event-birth"].Date)
	assert.Equal(t, "Family reunion (1955)", reloaded.Events["event-custom"].Title)

	// Idempotency at the fs boundary: a second invocation must be a no-op.
	require.NoError(t, migrateArchive(archivePath))
	second, err := os.ReadFile(archivePath)
	require.NoError(t, err)
	assert.Contains(t, string(second), "Birth of John Smith")
	assert.NotContains(t, string(second), "Birth of John Smith (1850)")
}
